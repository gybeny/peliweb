"""Validated runtime settings and script-owned configuration generation."""
from dataclasses import dataclass
from pathlib import Path
import os
import re

VERSION = "0.1.1"
TEMP_DIRS = ("client_temp", "proxy_temp", "fastcgi_temp", "uwsgi_temp", "scgi_temp")


@dataclass(frozen=True)
class Settings:
    port: int = 8080
    workers: int = 1
    connections: int = 1024
    keepalive: int = 65
    php_children: int = 8
    php_requests: int = 500
    php_idle: int = 10
    php_memory: int = 256
    php_upload: int = 64
    php_execution: int = 120
    log_level: str = "warn"
    access_log: bool = True

    @classmethod
    def from_env(cls, env=None):
        env = os.environ if env is None else env

        def integer(name, default, lower, upper):
            value = str(env.get(name, default))
            if not value.isascii() or not value.isdecimal() or not lower <= int(value) <= upper:
                raise ValueError(f"{name}: {lower}–{upper} közötti egész szám szükséges.")
            return int(value)

        level = env.get("WEBNEST_LOG_LEVEL", "warn")
        if level not in ("error", "warn", "notice", "info"):
            raise ValueError("WEBNEST_LOG_LEVEL: error, warn, notice vagy info lehet.")
        access = str(env.get("WEBNEST_ACCESS_LOG", "1"))
        if access not in ("0", "1"):
            raise ValueError("WEBNEST_ACCESS_LOG: 0 vagy 1 lehet.")
        return cls(
            port=integer("SERVER_PORT", 8080, 1024, 65535),
            workers=integer("WEBNEST_NGINX_WORKERS", 1, 1, 8),
            connections=integer("WEBNEST_NGINX_CONNECTIONS", 1024, 128, 16384),
            keepalive=integer("WEBNEST_KEEPALIVE_TIMEOUT", 65, 0, 300),
            php_children=integer("WEBNEST_PHP_CHILDREN", 8, 1, 128),
            php_requests=integer("WEBNEST_PHP_REQUESTS", 500, 1, 100000),
            php_idle=integer("WEBNEST_PHP_IDLE_TIMEOUT", 10, 1, 300),
            php_memory=integer("WEBNEST_PHP_MEMORY_MB", 256, 16, 4096),
            php_upload=integer("WEBNEST_PHP_UPLOAD_MB", 64, 1, 2048),
            php_execution=integer("WEBNEST_PHP_EXECUTION_TIME", 120, 1, 3600),
            log_level=level, access_log=access == "1",
        )


def quote(path: Path) -> str:
    return '"' + str(path).replace("\\", "\\\\").replace('"', '\\"') + '"'


def normalize_nginx(content: str, run: Path, settings: Settings) -> str:
    """Upgrade configurations generated by WebNest, not arbitrary nginx snippets.

    All five nginx temp paths must be writable, even if no uwsgi/scgi site
    exists. Alpine otherwise uses root-owned /var/lib/nginx/tmp locations.
    """
    if not re.search(r"(?m)^http\s*\{", content):
        raise ValueError("Hiányzik a WebNest nginx konfiguráció http blokkja.")
    top = {
        "worker_processes": str(settings.workers),
        "pid": quote(run / "nginx.pid"),
        "error_log": f"stderr {settings.log_level}",
    }
    for directive, value in top.items():
        pattern = rf"(?m)^{directive}\s+[^;\n]+;"
        if re.search(pattern, content):
            content = re.sub(pattern, lambda _: f"{directive} {value};", content, count=1)
        else:
            content = f"{directive} {value};\n" + content

    # These are managed HTTP-level directives in both old and new renderers.
    # Remove only lines that consist solely of a known directive.
    http_directives = (
        "client_body_temp_path", "proxy_temp_path", "fastcgi_temp_path",
        "uwsgi_temp_path", "scgi_temp_path", "access_log", "keepalive_timeout",
    )
    for directive in http_directives:
        content = re.sub(rf"(?m)^[ \t]*{directive}\s+[^;\n]+;[ \t]*\n?", "", content)
    preamble = "\n".join(
        f"    {directive} {quote(run / folder)};"
        for directive, folder in zip(http_directives[:5], TEMP_DIRS)
    )
    preamble += f"\n    keepalive_timeout {settings.keepalive};"
    preamble += (
        f"\n    access_log {quote(run / 'access.log')};\n"
        if settings.access_log else "\n    access_log off;\n"
    )
    content = re.sub(r"(?m)^http\s*\{[ \t]*(?:\r?\n[ \t]*)*", lambda _: "http {\n" + preamble, content, count=1)
    # The allocation is the single listener supported by the native renderer.
    content = re.sub(r"\blisten[ \t]+[0-9]+(?=[ \t;])", f"listen {settings.port}", content)
    return content


def bootstrap_nginx(home: Path, run: Path, settings: Settings) -> str:
    # Only the welcome file is exposed until domains/sites are deployed.
    config = f"""worker_processes 1;
pid nginx.pid;
error_log stderr warn;
events {{ worker_connections 1024; }}
http {{
    include mime.types;
    default_type application/octet-stream;
    server_tokens off;
    server {{
        listen {settings.port} default_server;
        server_name _;
        root {quote(home / 'sites/default/public')};
        location = / {{ try_files /index.html =404; }}
        location / {{ return 404; }}
    }}
}}
"""
    return normalize_nginx(config, run, settings)


def php_fpm(home: Path, run: Path, settings: Settings) -> str:
    return f"""[global]
pid = {run}/php-fpm.pid
error_log = {run}/php-fpm-error.log
daemonize = no

[www]
listen = 127.0.0.1:9000
pm = ondemand
pm.max_children = {settings.php_children}
pm.process_idle_timeout = {settings.php_idle}s
pm.max_requests = {settings.php_requests}
catch_workers_output = yes
decorate_workers_output = no
clear_env = yes
security.limit_extensions = .php
php_admin_flag[expose_php] = off
php_admin_flag[allow_url_include] = off
php_admin_flag[log_errors] = on
php_admin_value[error_log] = {run}/php-error.log
php_value[memory_limit] = {settings.php_memory}M
php_value[upload_max_filesize] = {settings.php_upload}M
php_value[post_max_size] = {settings.php_upload}M
php_value[max_execution_time] = {settings.php_execution}
"""


def apply_connections(content: str, settings: Settings) -> str:
    return re.sub(r"\bworker_connections\s+[0-9]+\s*;", f"worker_connections {settings.connections};", content)
